import { chromium, expect } from '@playwright/test';
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';

const executablePath = process.env.BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser = await chromium.launch({headless: true, ...(executablePath ? {executablePath} : {})});
const base = process.env.TEST_URL || 'http://127.0.0.1:4173';
const context = await browser.newContext({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
await context.addInitScript(() => { globalThis.__PACIFIC_API__ = true; });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let uploads = 0;
page.on('request', request => { if (request.url().endsWith('/api/datasets') && request.method() === 'POST') uploads++; });
const checks = [];
const pass = message => { checks.push(message); console.log('PASS ' + message); };
const username = 'browser_' + Date.now();
const password = 'test-only-password-' + Date.now();
try {
  await page.goto(base + '/#data');
  await expect(page.locator('#account-submit')).toBeEnabled();
  await page.locator('#csv-input').fill('name,lat,lng,value,category,date\nField north,15.5,120.9,0,mm,2026-11-01');
  await page.locator('#import-csv').click();
  await expect(page.locator('#csv-preview')).toContainText('Field north');
  expect(uploads).toBe(0);
  pass('Import stays local until explicit account save');
  await page.getByRole('button', {name: 'Create account', exact: true}).click();
  await page.locator('#account-username').fill(username);
  await page.locator('#account-password').fill(password);
  await page.locator('#account-submit').click();
  await expect(page.locator('#account-user')).toContainText(username);
  await page.locator('#dataset-name').fill('Browser fieldwork');
  await page.locator('#save-dataset').click();
  await expect(page.locator('#account-status')).toContainText('Saved 1 observations');
  await expect(page.locator('#saved-datasets')).toContainText('Browser fieldwork');
  expect(uploads).toBe(1);
  const cookies = await context.cookies();
  expect(cookies.find(cookie => cookie.name === 'pacific_session')?.httpOnly).toBe(true);
  pass('Account creation and database save use an HttpOnly session');
  await page.reload();
  await expect(page.locator('#account-user')).toContainText(username);
  await expect(page.locator('#saved-datasets')).toContainText('Browser fieldwork');
  await page.locator('#clear-csv').click();
  await expect(page.locator('#csv-preview')).toContainText('No observations');
  await page.locator('#saved-datasets').getByRole('button', {name: 'Open', exact: true}).click();
  await expect(page.locator('#csv-preview')).toContainText('Field north');
  await expect(page.locator('#csv-preview tbody tr').first()).toContainText('0');
  pass('Saved datasets and login survive page reload; reopening restores observations');
  await page.locator('#dataset-name').fill('Updated fieldwork');
  await page.locator('#save-dataset').click();
  await expect(page.locator('#saved-datasets')).toContainText('Updated fieldwork');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', {name: 'Download CSV', exact: true}).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/^observations-.*\.csv$/);
  pass('Updates and CSV exports use the saved database record');
  const outsider = await browser.newContext();
  try {
    const response = await outsider.request.get(base + '/api/datasets');
    expect(response.status()).toBe(401);
    const noCookie = await outsider.request.get(base + '/api/auth/me');
    expect((await noCookie.json()).user).toBe(null);
  } finally { await outsider.close(); }
  pass('Another browser cannot read a private workspace');
  await page.locator('#account-logout').click();
  await expect(page.locator('#account-submit')).toBeVisible();
  await page.locator('#account-username').fill(username);
  await page.locator('#account-password').fill(password);
  await page.locator('#account-submit').click();
  await expect(page.locator('#saved-datasets')).toContainText('Updated fieldwork');
  pass('Sign-out revokes the session and password sign-in restores the account');
  await page.setViewportSize({width: 390, height: 844});
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo({top: 0, behavior: 'instant'}); });
  await page.screenshot({path: '.artifacts/fullstack-mobile.png', fullPage: true});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.locator('#saved-datasets').getByRole('button', {name: 'Delete', exact: true}).click();
  await page.getByRole('button', {name: 'Confirm delete', exact: true}).click();
  await expect(page.locator('#saved-datasets')).toContainText('No saved datasets');
  await expect(page.locator('#csv-preview')).toContainText('Field north');
  pass('Mobile account layout and explicit deletion preserve local observations');
  expect(errors).toEqual([]);
  await mkdir('.artifacts', {recursive: true});
  await writeFile('.artifacts/fullstack-report.json', JSON.stringify({checks, errors}, null, 2));
} finally { await browser.close(); }
